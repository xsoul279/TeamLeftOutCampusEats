from datetime import datetime
from zoneinfo import ZoneInfo
import secrets

from flask import (
    Blueprint, abort, flash, redirect, render_template, request, url_for,
)
from flask_login import current_user, login_required
from sqlalchemy.exc import SQLAlchemyError
from sqlalchemy import select

from .extensions import db
from .models import DietaryTag, Listing, Reservation, ReservationStatus

listings_bp = Blueprint("listings", __name__)

def make_pickup_code():
    char_bank = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
    while True:
        code = ""
        for _ in range(6):
            code += secrets.choice(char_bank)
        # Find one reservation with this code. If none exist, return the code. Otherwise, generate a new one.
        taken = db.session.scalar(select(Reservation).where(Reservation.pickup_code == code))
        if not taken:
            return code

@listings_bp.get("/listings")
@login_required
def browse_listings():
    if current_user.role != "student":
        abort(403, description="Only students can browse listings.")

    now = datetime.now(ZoneInfo("America/Denver")).replace(tzinfo=None)
    available = (
        Listing.cancelled.is_(False),
        Listing.pickup_end > now,
        Listing.portions_remaining > 0,
    )

    # US8: filter by dietary tags (all must match) and pickup location.
    # AI use: Generated by Claude, Reviewed & Approved by Me
    selected_tags = [
        DietaryTag[name] for name in request.args.getlist("tag")
        if name in DietaryTag.__members__
    ]
    location = request.args.get("location", "").strip()

    query = select(Listing).where(*available)
    if selected_tags:
        query = query.where(Listing.tags.contains(selected_tags))
    if location:
        query = query.where(Listing.pickup_location == location)
    listings = db.session.scalars(query.order_by(Listing.pickup_end)).all()

    locations = db.session.scalars(
        select(Listing.pickup_location).where(*available)
        .distinct().order_by(Listing.pickup_location)
    ).all()
    if location and location not in locations:
        locations.append(location)

    return render_template(
        "listings.html",
        listings=listings,
        dietary_tags=list(DietaryTag),
        selected_tags=selected_tags,
        locations=locations,
        location=location,
        filtering=bool(selected_tags or location),
    )

@listings_bp.post("/listings/<int:listing_id>/reserve")
@login_required
def reserve_listing(listing_id):
    # Check if the user is a student
    if current_user.role != "student":
        abort(403, description="Only students can reserve listings.")
    # Lock the listing row for update to prevent multiple students from reserving the same portions simultaneously
    listing = db.session.get(Listing, listing_id, with_for_update=True)
    # Check if the listing exists
    if not listing:
        abort(404, description="Listing not found.")
    now = datetime.now(ZoneInfo("America/Denver")).replace(tzinfo=None)
    # Check if the listing is cancelled or the pickup end time has passed
    if listing.cancelled or listing.pickup_end <= now:
        flash("This listing is no longer available.", "error")
        return redirect(url_for("listings.browse_listings"))
    existing = db.session.scalar(select(Reservation).where(
        Reservation.student_id == current_user.id,
        Reservation.listing_id == listing.id,
        Reservation.status == ReservationStatus.ACTIVE
    ))
    # Check if the student already has an active reservation for this listing
    if existing:
        flash("You already have a reservation for this listing.", "error")
        return redirect(url_for("listings.browse_listings"))
    # Check if the requested number of portions is valid and available
    try:
        portions = int(request.form.get("portions", ""))
        if portions not in (1, 2):
            raise ValueError
        if portions > listing.portions_remaining:
            flash("Not enough portions remaining to reserve.", "error")
            return redirect(url_for("listings.browse_listings"))
    except ValueError:
        flash("Invalid number of portions requested.", "error")
        return redirect(url_for("listings.browse_listings"))
    # Update the listing's portions_remaining
    listing.portions_remaining -= portions
    # Create a new reservation for the student
    reservation = Reservation(
            student_id=current_user.id,
            listing_id=listing.id,
            portions = portions,
            pickup_code=make_pickup_code()
        )
    # Add the reservation to the database and commit the changes
    db.session.add(reservation)
    
    try:
        db.session.commit()
    except SQLAlchemyError:
        db.session.rollback()
        flash("Something went wrong reserving this listing. Please try again.", "error")
        return redirect(url_for("listings.browse_listings"))

    return redirect(url_for("listings.reservation_confirmed", reservation_id=reservation.id))

@listings_bp.get("/reservations/<int:reservation_id>")
@login_required
def reservation_confirmed(reservation_id):
    reservation = db.session.get(Reservation, reservation_id)
    if not reservation or reservation.student_id != current_user.id:
        abort(404, description="Reservation not found.")
    return render_template("reservation_confirmed.html", reservation=reservation)

@listings_bp.route("/listings/new", methods=["GET", "POST"])
@login_required
def new_listing():
    if current_user.role != "vendor":
        abort(403, description="You do not have permission to create a listing.")

    def show_form(status=200):
        return render_template("new_listing.html", dietary_tags=list(DietaryTag),), status

    if request.method == "GET":
        return show_form()

    title = request.form.get("title", "").strip()
    description = request.form.get("description", "").strip()
    location = request.form.get("pickup_location", "").strip()
    errors = []

    if not title or len(title) >120:
        errors.append("Title is required and must be less than 120 characters.")
    if not description:
        errors.append("Description is required.")
    if not location or len(location) > 200:
        errors.append("Enter a valid pickup location of 1 to 200 characters")

    try:
        portions = int(request.form.get("portions", ""))
        if not 1 <= portions <= 100:
            raise ValueError
    except ValueError:
        errors.append("Portions must be a number between 1 and 100.")
    tags = []

    for tag_name in set(request.form.getlist("tags")):
        try:
            tags.append(DietaryTag[tag_name])
        except KeyError:
            errors.append(f"Invalid dietary tag: {tag_name}")

    try:
        start = datetime.fromisoformat(request.form.get("pickup_start", ""))
        end = datetime.fromisoformat(request.form.get("pickup_end", ""))

        if start.tzinfo is not None or end.tzinfo is not None:
            raise ValueError

        now = datetime.now(ZoneInfo("America/Denver")).replace(tzinfo=None)

        if end <= start:
             errors.append("Pickup end time must be after pickup start time.")
        if start < now:
            errors.append("Pickup start time must be in the future.")
        if end <= now:
            errors.append("Pickup end time must be in the future.")
    except ValueError:
        errors.append("Invalid pickup start or end time.")

    if errors:
        for error in errors:
            flash(error, "error")
        return show_form(400)

    listing = Listing(
        vendor_id=current_user.id,
        title=title,
        description=description,
        portions=portions,
        portions_remaining=portions,
        pickup_location=location,
        pickup_start=start,
        pickup_end=end,
        tags=tags,
    )
    db.session.add(listing)

    try:
        db.session.commit()
    except SQLAlchemyError:
        db.session.rollback()
        flash("An error occurred while creating the listing.", "error")
        return show_form(500)

    flash("Listing created successfully.", "success")
    return redirect(url_for("listings.new_listing"))
            